// Защита от повторной оплаты ОДНОГО пользовательского действия — см. п.15 аудита AI-себестоимости:
// двойной тап по кнопке отправки, повторный сабмит формы, разрыв сети с ретраем клиента не должны
// приводить к двум платным AI-вызовам за одно и то же сообщение. Клиент (index.html) уже не даёт
// начать новую отправку, пока не закончилась предыдущая (aiChat.status!=='idle'), но это только
// UX-подсказка внутри одной вкладки — сюда же может прийти повтор из-за сетевого ретрая или
// открытой второй вкладки/устройства, так что серверная проверка отдельно от клиентской.
//
// Реализация — в памяти изолята Worker'а, не в Firestore: для личного проекта нет смысла тратить
// round-trip к БД на КАЖДЫЙ AI-запрос ради защиты от секундных дублей, а изолят Cloudflare Workers
// обычно живёт достаточно, чтобы поймать именно двойной тап/ретрай (окно в несколько секунд).
// Технический долг: если Worker уйдёт на новый изолят между двумя попытками (холодный старт),
// дубль не будет пойман — для настоящей гарантии "ровно один раз" нужен был бы Firestore-документ
// с транзакцией, что для текущего масштаба (один активный пользователь на сессию) избыточно.
const recentTurns = new Map(); // `${uid}:${text}` -> timestamp мс последнего запуска
const DEDUPE_WINDOW_MS = 4000;

function cleanup(now) {
  for (const [key, ts] of recentTurns) {
    if (now - ts > DEDUPE_WINDOW_MS) recentTurns.delete(key);
  }
}

// true — этот же uid прислал этот же текст меньше DEDUPE_WINDOW_MS назад, обрабатывать не нужно
// (вызывающий код должен молча выйти без нового AI-вызова). false — первый раз, дальше можно идти
// в planTurn как обычно; сам факт вызова сразу же засчитывается, чтобы гонка из двух параллельных
// запросов не проскочила оба разом.
export function isDuplicateTurn(uid, text) {
  const now = Date.now();
  cleanup(now);
  const key = `${uid}:${String(text || '').trim().toLowerCase().slice(0, 200)}`;
  if (recentTurns.has(key)) return true;
  recentTurns.set(key, now);
  return false;
}
