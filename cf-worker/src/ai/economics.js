// Бизнес-параметры AI-экономики — единственное место с этими числами (см. п.19 аудита
// AI-себестоимости: "не зашивать жёстко в бизнес-логику"). Отдельно от pricing.js: там —
// реальные тарифы Yandex (то, что нам ВЫСТАВЛЯЮТ), здесь — то, что мы сами для себя ЦЕЛИМ по
// подписке. Правь эти три числа при изменении цены подписки, ничего больше в проекте менять
// не нужно.
export const AI_ECONOMICS = {
  subscriptionPriceRub: 250,
  targetMonthlyAiCostRub: 35, // желаемая себестоимость AI на платящего пользователя, середина диапазона 30–40 ₽
  maxAverageMonthlyAiCostRub: 50, // допустимый СРЕДНИЙ максимум по всей базе — не индивидуальный лимит (см. п.20 аудита)
};

// Грубая классификация "как далеко пользователь от целевой себестоимости" — используется, чтобы
// РЕШИТЬ, насколько щедрым может быть AI для конкретного пользователя (меньше Pro/контекста при
// повышенном расходе), а не чтобы жёстко блокировать Atlas ровно на 50 ₽ (см. п.20 аудита:
// "нужно позволить существовать тяжёлым пользователям, пока экономика всей базы остаётся
// нормальной"). Обычные функции (финансы/события/привычки/factual queries) всегда остаются
// доступны на всех трёх уровнях — ограничивается только то, что и так дорогое (Pro-анализ).
export function usageTier(monthToDateCostRub) {
  const cost = Number(monthToDateCostRub) || 0;
  if (cost < AI_ECONOMICS.targetMonthlyAiCostRub) return 'normal';
  if (cost < AI_ECONOMICS.maxAverageMonthlyAiCostRub) return 'elevated';
  return 'extreme';
}
